def add(
    category: str,
    target_text: str,
    annotations: list[dict],
    *,
    context_before: tuple[str, ...] = (),
    context_after: tuple[str, ...] = (),
    ambiguous: bool = False,
    expected_utterance: str = "",
    expect_no_issue: bool = False,
    notes: str = "",
) -> None:
    """Добавляет кейс, вычисляя границы аннотаций по исходной строке.

    Границы считаются здесь, а не пишутся руками: gold, в котором span не
    совпадает с текстом, ломает все метрики сразу, и человек такие ошибки в
    трёхстах строках не вычитает.
    """
    _counter["n"] += 1
    prefix = {
        CATEGORY_HOMOGRAPH: "homograph",
        CATEGORY_YO: "yo",
        CATEGORY_MORPHOLOGY: "morphology",
        CATEGORY_NAME: "name",
        CATEGORY_TOPONYM: "toponym",
        CATEGORY_ABBREVIATION: "abbreviation",
        CATEGORY_NUMBER: "number",
        CATEGORY_LATIN: "latin",
        CATEGORY_TERM: "term",
        CATEGORY_DIALOGUE: "dialogue",
        CATEGORY_SHORT: "short",
        CATEGORY_NEGATIVE: "no_issue",
    }[category]
    case_id = f"{prefix}-{_counter['n']:04d}"
    expected: list[Annotation] = []
    for item in annotations:
        source = item["source"]
        occurrence = item.get("occurrence", 0)
        try:
            start, actual = _find_span(target_text, source, occurrence)
        except ValueError as exc:
            # Собираем все расхождения сразу: править таблицы по одному кейсу
            # за прогон — долго и легко пропустить ошибку.
            SPAN_PROBLEMS.append(f"{case_id}: {exc}")
            continue
        expected.append(
            Annotation(
                span_start=start,
                span_end=start + len(actual),
                source=actual,
                type=item["type"],
                meaning=item.get("meaning", ""),
                suggested_form=item.get("suggested_form", ""),
                confidence=float(item.get("confidence", 0.9)),
                needs_review=bool(item.get("needs_review", False)),
                reason_code=item.get("reason_code", ""),
            )
        )
    CASES.append(
        DatasetCase(
            id=case_id,
            category=category,
            target_text=target_text,
            expected=tuple(sorted(expected, key=lambda item: item.span_start)),
            context_before=context_before,
            context_after=context_after,
            ambiguous=ambiguous,
            expect_no_issue=expect_no_issue,
            expected_utterance=expected_utterance,
            notes=notes or expected_utterance,
        )
    )


def _find_span(text: str, source: str, occurrence: int) -> tuple[int, str]:
    """Ищет `source` в тексте без учёта регистра и возвращает (начало, факт. форма).

    Регистр не должен быть заботой таблиц: слово в начале предложения пишется с
    заглавной, а `source` в gold обязан совпадать с `text[span_start:span_end]`
    **посимвольно**. Поэтому источником становится найденный фрагмент, а таблица
    задаёт лишь слово для поиска.
    """
    lowered = text.lower()
    needle = source.lower()
    start = -1
    for _ in range(occurrence + 1):
        start = lowered.find(needle, start + 1)
        if start < 0:
            raise ValueError(f"«{source}» не найдено в «{text}» (вхождение {occurrence})")
    return start, text[start : start + len(source)]


