"""Проактивная проверка бюджета памяти перед загрузкой движка.

`resource_guard` реагирует **постфактум**: он замечает перегрузку, когда память
уже занята, и прерывает текущую задачу. Здесь проверка идёт **до** подъёма весов.
Причина — пик в E2E: на 18 ГБ «F5 + XTTS-banana + Whisper» доводили систему до
90.5 %, а это уже зона swap. На MPS это особенно неприятно: система не бросает
исключение об исчерпании памяти, а уходит в подкачку, и следующая задача просто
ждёт. Отказ с внятным текстом дешевле такой задачи.

Источник правды по памяти один и тот же — `psutil.virtual_memory()`; им же
пользуется `memory_monitor`, поэтому guard и сводка в `/api/status` не расходятся.
Здесь нет своей копии расчёта «сколько занято», только пороги.

Правила, в порядке проверки:

1. политика «не более N TTS-движков» (`MAX_CONCURRENT_TTS_ENGINES`);
2. запас свободной памяти: вес движка плюс буферы обязаны помещаться в доступное;
3. голова после загрузки: `MIN_FREE_SYSTEM_PERCENT` % свободной памяти обязано
   остаться системе — иначе один большой движок выедает запас целиком.

Перегрузка (`SYSTEM_PRESSURE_PERCENT`) сама по себе не отказ: если по первым
правилам места хватает, загрузка разрешается, но пишется предупреждение — без
него система, работающая на пределе, не оставляла бы следа в журнале.

Whisper в лимит TTS-движков не входит: он транзиентный (живёт в своём процессе
только на время распознавания), и считать его третьим движком значило бы
отклонять законную проверку качества. Но при его подъёме поверх двух TTS пишется
предупреждение — в пике он занимает ~1.5 ГБ.
"""

from __future__ import annotations

import logging
import os

import psutil

from . import config

logger = logging.getLogger("tts.memory_guard")

# Запас поверх веса модели: буферы инференса, временные тензоры и пик при
# загрузке весов. Не «на глаз»: у F5 честный инференс добавляет к весам сотни
# мегабайт, и проверка «ровно по размеру файла» пропускала бы загрузку, которой
# места на самом деле не хватает.
ENGINE_MEMORY_SLACK_MB = 512


class MemoryBudgetExceeded(RuntimeError):
    """Недостаточно памяти для загрузки нового движка.

    Наследник `RuntimeError`: вызывающий (роут) отличает её от прочих отказов и
    отдаёт `409` с текстом, в котором сказано, что именно освободить.
    """


def check_engine_load_budget(
    engine_id: str,
    current_loaded: list[str],
    engine_size_mb: int,
) -> None:
    """Проверяет, можно ли загрузить движок, не выходя за бюджет.

    Вызывается **до** начала загрузки весов. Если бюджет превышен — поднимает
    `MemoryBudgetExceeded` с текстом, по которому пользователю понятно, что
    сделать. Ничего не логирует об успехе: это горячий путь загрузки, а не
    отчёт.

    `current_loaded` — **другие** уже поднятые TTS-движки (без загружаемого):
    иначе повторная загрузка уже поднятого движка упиралась бы в собственный
    счётчик.
    """
    # 1. Политика «не более N движков».
    if len(current_loaded) >= config.MAX_CONCURRENT_TTS_ENGINES:
        raise MemoryBudgetExceeded(
            f"Уже загружено {len(current_loaded)} TTS-движков "
            f"({', '.join(current_loaded)}); лимит — "
            f"{config.MAX_CONCURRENT_TTS_ENGINES}. "
            f"Выгрузите один из них (вкладка «Модели») перед загрузкой "
            f"«{engine_id}»."
        )

    # 2. Бюджет свободной памяти системы.
    vm = psutil.virtual_memory()
    free_mb = vm.available / (1024 * 1024)
    required_mb = engine_size_mb + ENGINE_MEMORY_SLACK_MB

    if free_mb < required_mb:
        raise MemoryBudgetExceeded(
            f"Недостаточно свободной памяти для «{engine_id}»: "
            f"нужно ~{required_mb} МБ, доступно {free_mb:.0f} МБ "
            f"(система занята на {vm.percent:.0f}%). "
            f"Закройте лишние приложения или выгрузите неиспользуемый "
            f"движок."
        )

    # 3. Голова после загрузки: часть свободной памяти обязана остаться системе,
    # а не уйти движку целиком. Без этого правила движок на 5.2 ГБ проходил бы
    # проверку «помещается в доступное», оставляя систему без запаса на чужие
    # процессы — то есть ровно в том состоянии, ради которого guard и заведён.
    headroom_mb = free_mb * config.MIN_FREE_SYSTEM_PERCENT / 100
    if free_mb - required_mb < headroom_mb:
        raise MemoryBudgetExceeded(
            f"После загрузки «{engine_id}» системе не останется запаса: "
            f"свободно {free_mb:.0f} МБ, движку нужно ~{required_mb} МБ, "
            f"а запас должен быть не меньше {headroom_mb:.0f} МБ "
            f"({config.MIN_FREE_SYSTEM_PERCENT}% свободного). "
            f"Выгрузите неиспользуемый движок или закройте лишние приложения."
        )

    # 4. Системное давление (процент занятой памяти) — предупреждение, не отказ.
    if vm.percent >= config.SYSTEM_PRESSURE_PERCENT:
        logger.warning(
            "Система под давлением памяти: %.0f%% занято (порог %d%%). "
            "Загрузка «%s» разрешена, но возможны задержки.",
            vm.percent,
            config.SYSTEM_PRESSURE_PERCENT,
            engine_id,
        )


def check_whisper_load_budget(current_tts: list[str]) -> None:
    """Whisper транзиентный, но в пике он ест ~1.5 ГБ.

    Если оба TTS уже в памяти — Whisper поднимать можно (он работает в своём
    процессе и уходит вместе с ним), но при занятой системе об этом стоит
    сказать в журнале: пик «два движка + распознавание» и был тем случаем, из
    которого выросла эта политика.

    Отказывать здесь нельзя: распознавание — часть проверки качества, и запрет
    по памяти сделал бы её недоступной именно на слабых машинах, где она нужнее
    всего.
    """
    vm = psutil.virtual_memory()
    if vm.percent >= config.SYSTEM_PRESSURE_PERCENT:
        logger.info(
            "Whisper будет поднят поверх %d TTS-движков при занятости %.0f%%; "
            "это может вызвать давление на память.",
            len(current_tts),
            vm.percent,
        )


def loaded_tts_engines() -> list[str]:
    """Уже поднятые TTS-движки — по реестру, без создания новых.

    `created_engines()` отдаёт только созданные движки, поэтому проверка не
    поднимает модель: вкладка «Модели» и роут загрузки обязаны оставаться
    дешёвыми.
    """
    from .engines.registry import created_engines

    return sorted(
        engine_id for engine_id, engine in created_engines().items() if engine.is_loaded
    )


def engine_size_mb(engine_id: str) -> int | None:
    """Оценка веса движка в МБ из паспорта модели — `None`, если паспорта нет.

    Паспорта (а не файлы на диске): у движка может быть несколько моделей
    (у Qwen3-TTS — основание и токен-декодер), и брать нужно их сумму. Если
    движок не описан в реестре моделей, судить о его весе нечем — вызывающий
    решает, что делать (см. `guard_engine_load`).
    """
    from .model_manager import model_specs

    sizes = [spec.approx_size_bytes for spec in model_specs() if spec.engine_id == engine_id]
    if not sizes:
        return None
    return int(sum(sizes) / (1024 * 1024))


def guard_engine_load(engine_id: str) -> None:
    """Проверка бюджета по живому состоянию процесса — точка входа для вызовов.

    Собирает то, что нужно `check_engine_load_budget`: список **других** поднятых
    движков и вес загружаемого из паспорта. Отсюда зовут роут загрузки и
    пайплайн (перед ленивым `load()`), поэтому «почему отказано» объясняется
    одним и тем же кодом.

    Два выхода без проверки:

    * дочерний процесс воркера — бюджет считает родитель, у него видно все
      движки, тогда как воркер знает только о своём; повторная проверка в ребёнке
      могла бы отклонить уже разрешённую загрузку;
    * движок без паспорта модели — сравнивать не с чем.
    """
    if os.environ.get(config.WORKER_CHILD_ENV):
        return
    size_mb = engine_size_mb(engine_id)
    if size_mb is None:
        logger.debug("Движок %s: паспорта модели нет, бюджет памяти не проверяю", engine_id)
        return
    current = [loaded for loaded in loaded_tts_engines() if loaded != engine_id]
    check_engine_load_budget(engine_id, current, size_mb)
