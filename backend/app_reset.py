"""Сброс из интерфейса: кеш приложения, текущий проект и настройки вкладок.

Две ступени, и обе ограничены явным списком того, что удаляется:

- ``cache`` — то же, что ручная очистка вкладки `05` «Модели»: транзитные файлы
  `output/`, результаты сравнения движков и временные остатки. Логика не
  дублируется, а вызывается (`cache_cleanup.clear`): вторая реализация очистки
  однажды разошлась бы с первой, и «очистить» из двух мест означало бы разное;
- ``full`` — ступень выше: тот же кеш плюс данные и настройки той вкладки, из
  которой сброс запущен. Во вкладке диалога это открытый проект (текст, спикеры,
  реплики, take'ы — всё, что пользователь набрал для этого диалога), а в обеих
  вкладках вместе с ним сбрасываются общие настройки анализатора.

Почему проект, а не «всё сразу»: удалять проекты, которых пользователь сейчас не
видит, — это не сброс вкладки, а потеря работы, о которой никто не просил. Список
проектов переживает сброс, открытым остаётся пустой проект.

Граница проведена по одному признаку: **созданное пользователем не удаляется**.
Неприкосновенны и не могут быть задеты ни при каком сочетании аргументов:

- ``voices/`` и ``voices.json`` — записанные с микрофона и загруженные голоса;
- ``pronunciation_entries`` — глобальный словарь произношения (правило «SQL
  читается как эскьюэль» задано один раз и работает во всех диалогах);
- ``models/`` и кеш ``huggingface_hub`` — веса: их удаление требует интернета на
  повторную загрузку и остаётся отдельным потоком во вкладке `05` «Модели».

Словарь проекта (``project_pronunciation_entries``) уходит вместе с проектом: он
привязан к конкретному тексту и без него смысла не имеет. Глобальный словарь при
этом цел — как и голоса.
"""

import logging

from . import cache_cleanup, diagnostics
from .db.store import get_projects_store
from .llm import settings_store

logger = logging.getLogger(__name__)

# Ступени сброса. Имена совпадают с ключами протокола, чтобы интерфейсу не
# приходилось держать вторую таблицу переводов.
SCOPE_CACHE = "cache"
SCOPE_FULL = "full"
SCOPES = (SCOPE_CACHE, SCOPE_FULL)

# Вкладки, из которых сброс запускается. Список закрытый: сброс «вообще всего» —
# это не вкладка, а удаление данных, о котором пользователь не просил.
TAB_DIALOGUE = "dialogue"
TAB_TEXT = "text"
TABS = (TAB_DIALOGUE, TAB_TEXT)


def reset(scope: str, tab: str | None = None, project_id: str | None = None) -> dict:
    """Выполняет сброс выбранной ступени и отчитывается о каждом шаге.

    Отчёт содержит ровно то, что произошло: сколько освобождено, какой проект
    удалён, сколько архивов диагностики ушло вместе с ним и сброшены ли настройки
    анализатора. Интерфейс показывает его дословно, поэтому «сброшено» в ответе
    означает выполненное действие, а не намерение.

    Неизвестная ступень или вкладка — ошибка вызывающего (API отвечает на неё 400
    раньше): молча вернуть пустой отчёт значило бы сделать вид, что сброс был.
    Отсутствующий проект ошибкой не считается: сброс без открытого проекта — это
    нормальный случай «сбрасывать нечего», и он виден в ответе (`project_deleted`).
    """
    if scope not in SCOPES:
        raise ValueError(
            f"Неизвестная ступень сброса: {scope}. Доступны: " + ", ".join(SCOPES)
        )
    if scope == SCOPE_FULL and tab not in TABS:
        raise ValueError(
            f"Неизвестная вкладка сброса: {tab}. Доступны: " + ", ".join(TABS)
        )

    report = {
        "scope": scope,
        "tab": tab if tab in TABS else None,
        "cache": cache_cleanup.clear(cache_cleanup.TARGETS),
        "project_deleted": None,
        "diagnostics_deleted": 0,
        "llm_settings_reset": False,
    }
    if scope == SCOPE_CACHE:
        return report

    if tab == TAB_DIALOGUE:
        report["project_deleted"], report["diagnostics_deleted"] = _drop_project(project_id)
    report["llm_settings_reset"] = _reset_llm_settings()
    logger.info(
        "Сброс (%s, вкладка %s): освобождено %.2f МБ, проект %s, архивов диагностики %s, "
        "настройки анализатора сброшены: %s",
        scope, tab, report["cache"]["total_mb"], report["project_deleted"],
        report["diagnostics_deleted"], report["llm_settings_reset"],
    )
    return report


def _drop_project(project_id: str | None) -> tuple[str | None, int]:
    """Удаляет проект целиком вместе с его файлами и архивами диагностики.

    Возвращает `(id удалённого проекта, число удалённых архивов)`. Архивы
    удаляются **до** проекта: их список строится по проекту, и после удаления
    строки в базе эти файлы стали бы недостижимыми — ни открыть, ни убрать из
    интерфейса, потому что все роуты диагностики начинаются с проверки проекта.

    Файлы take'ов и каталог проекта убирает `ProjectsStore.delete_project`: это
    тот же путь, что и у кнопки удаления проекта, и второй его копии быть не должно.
    """
    if not project_id:
        return None, 0
    store = get_projects_store()
    project = store.get_project(project_id)
    if project is None:
        logger.info("Сброс: проект %s уже удалён — удалять нечего", project_id)
        return None, 0
    removed = diagnostics.clear_archives(project)
    if not store.delete_project(project_id):
        return None, removed
    return project_id, removed


def _reset_llm_settings() -> bool:
    """Возвращает настройки анализатора к значениям окружения.

    Файл `data/llm_settings.json` перекрывает окружение, поэтому «сбросить» здесь
    означает именно удалить его: записывать в него значения по умолчанию значило
    бы зафиксировать их как выбор пользователя и перестать видеть изменения
    `LLM_*` в окружении. Нет файла — сбрасывать нечего, это не ошибка.

    Это настройка приложения, а не проекта, поэтому она сбрасывается из обеих
    вкладок: галочка «анализировать текст» относится и к диалогу, и к сплошному
    тексту — один Analyzer на обе вкладки.
    """
    path = settings_store.settings_path()
    try:
        path.unlink()
    except FileNotFoundError:
        return False
    except OSError as exc:
        # Настройку не сбросить (например, каталог только для чтения) — об этом
        # честно скажет `false` в отчёте, а не «сброшено» на словах.
        logger.warning("Не удалось сбросить настройки анализатора (%s): %s", path, exc)
        return False
    return True
