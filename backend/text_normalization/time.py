"""Время: «12:30» — это часы и минуты, а не два числа через двоеточие.

Политика чтения выбрана одна и документируется здесь, потому что от неё зависит
и тест, и ожидание пользователя:

* «12:30» → «двенадцать часов тридцать минут» — обе части читаются и
  согласуются: «12:01» → «двенадцать часов одна минута»;
* «12:00» → «двенадцать часов» — нулевые минуты не читаются: «ноль минут» в
  речи звучит неестественно;
* «00:05» → «ноль часов пять минут» — час остаётся, даже нулевой.

Альтернатива «двенадцать ноль пять» короче, но требует отдельной таблицы чтения
минут с ведущим нулём, а выигрыш только в длине фразы. Выбран первый вариант:
он единообразен для :00, :05 и :30.

Невалидное время («25:99») не трогается и не разваливается на два числа — оно
прячется в плейсхолдер до шага чисел.
"""

import re

from .morphology import agree

CLOCK_RE = re.compile(r"(?<![\d:])(\d{1,2}):(\d{2})(?![\d:])")

HOURS_FORMS = ("час", "часа", "часов")
MINUTES_FORMS = ("минута", "минуты", "минут")


def expand_time(text: str, protect=None) -> str:
    """Разворачивает время словами; невалидное отдаёт в `protect`, если он есть."""

    def replace(match: re.Match) -> str:
        hours, minutes = int(match.group(1)), int(match.group(2))
        if hours > 23 or minutes > 59:
            return protect(match.group()) if protect is not None else match.group()
        clock = agree(hours, HOURS_FORMS)
        if minutes == 0:
            return clock
        return f"{clock} {agree(minutes, MINUTES_FORMS, gender='f')}"

    return CLOCK_RE.sub(replace, text)
