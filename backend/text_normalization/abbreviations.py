"""Сокращения и знак номера: «т.е.», «руб.», «ул.», «№ 15».

Пары «шаблон → разворот» идут сверху вниз, поэтому многоточечные сокращения
стоят раньше одинарных: иначе «т.д.» распалось бы на «т» и «д». Каждое
сокращение ищется как отдельное слово, а не как подстрока: «др.» внутри «мудр.»
— не сокращение, а «см» внутри «смех» — не сантиметры.

Шаг идёт после единиц и денег: «5 км» уже стало «пять километров», и таблица
здесь нужна только для сокращений без числа перед ними.
"""

import logging
import re

from .morphology import cardinal
from .numbers import number_value

logger = logging.getLogger(__name__)

# Пары «шаблон → разворот». По одному шаблону за раз, а не общим регэкспом:
# замены — это готовый текст, и общий алфавитный разбор пришлось бы держать
# отдельной таблицей соответствия, которую легко рассинхронизировать.
ABBREVIATIONS: tuple[tuple[str, str], ...] = (
    (r"т\.\s*е\.", "то есть"),
    (r"т\.\s*д\.", "так далее"),
    (r"т\.\s*п\.", "тому подобное"),
    (r"т\.\s*к\.", "так как"),
    (r"т\.\s*н\.", "так называемый"),
    (r"т\.\s*о\.", "таким образом"),
    (r"н\.\s*э\.", "нашей эры"),
    (r"г\.\s*г\.", "годы"),
    (r"им\.", "имени"),
    (r"напр\.", "например"),
    (r"рис\.", "рисунок"),
    (r"стр\.", "страница"),
    (r"др\.", "другие"),
    (r"руб\.", "рублей"),
    (r"коп\.", "копеек"),
    (r"тыс\.", "тысяч"),
    (r"чел\.", "человек"),
    (r"мин\.", "минут"),
    (r"сек\.", "секунд"),
    (r"кв\.", "квартира"),
    (r"ул\.", "улица"),
    (r"млн\b", "миллионов"),
    (r"млрд\b", "миллиардов"),
    (r"км\b", "километров"),
    (r"кг\b", "килограммов"),
    (r"мм\b", "миллиметров"),
    (r"см\b", "сантиметров"),
)
# Аббревиатуру ищем как отдельное слово, а не как подстроку: «др.» внутри
# «мудр.» — не сокращение, а «см» внутри «смех» — не сантиметры.
ABBREVIATION_ANCHOR = r"(?<![0-9A-Za-zА-Яа-яЁё])"

# Знак номера — отдельная замена, потому что за ним идёт число, которое надо
# прочитать словами: «№ 15» → «номер пятнадцать». Решётка «#» сюда не входит.
NUMBER_SIGN_RE = re.compile(r"№\s*(\d+(?:[.,]\d+)?)")


def expand_number_sign(text: str) -> str:
    """«№ 15» → «номер пятнадцать»; «#» остаётся нетронутым."""

    def replace(match: re.Match) -> str:
        return f"номер {cardinal(number_value(match.group(1)))}"

    return NUMBER_SIGN_RE.sub(replace, text)


def expand_abbreviations(text: str) -> str:
    """Разворачивает сокращения по списку сверху вниз."""
    for pattern, replacement in ABBREVIATIONS:
        text = re.sub(ABBREVIATION_ANCHOR + pattern, replacement, text, flags=re.IGNORECASE)
    return text
